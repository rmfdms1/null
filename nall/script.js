let current = 0;

function updateUI() {
  const bar = document.querySelector(".progress-bar");
  const width = bar.offsetWidth - 60; // 로켓 크기 보정
  const step = current / (steps.length - 1);
  const leftPos = step * width;

  rocket.style.left = `${leftPos}px`;
  description.innerText = steps[current];

  // 반짝임 효과
  starFlash.style.left = `${leftPos + 20}px`;
  starFlash.style.opacity = 1;
  starFlash.style.top = "30px";
  setTimeout(() => {
    starFlash.style.opacity = 0;
  }, 400);
}

function nextStep() {
  if (current < steps.length - 1) {
    current++;
    updateUI();
  }
}

function prevStep() {
  if (current > 0) {
    current--;
    updateUI();
  }
}

window.onload = updateUI;
